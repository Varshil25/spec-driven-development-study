"""synthesize.py: question pages (LLM), then FAQ and index (deterministic) from the source articles.

Usage: python3 scripts/synthesize.py [--only Q2] [--force]
A question page is rebuilt only when an article it draws on, or the spec, changed.
"""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402
import llm  # noqa: E402

SYSTEM = """You write one question page of an OpenOwls SD-KDP knowledge base, in the Oracle's voice.
Use ONLY the source articles given; cite them with their tags such as [S03]; keep every evidence-class label.
Follow the question-page template in output-format.md exactly, all sections present ("Nothing in the corpus." where empty).
Output only the page body in Markdown, starting with the '# ' title line. No front matter."""


def articles():
    out = {}
    for path in sorted((common.WIKI / "sources").glob("S*.md")):
        meta, body = common.read_front_matter(path.read_text(encoding="utf-8"))
        out[meta.get("id", path.stem)] = (meta, body)
    return out


def key_questions():
    text = (common.SPECS / "oracle.md").read_text(encoding="utf-8")
    return dict(re.findall(r"^\|\s*(Q[1-8])\s*\|\s*(.+?)\s*\|\s*$", text, flags=re.M))


def relevant(arts, q):
    return {sid: a for sid, a in arts.items() if q in (a[0].get("questions") or [])}


def inputs_hash(arts, ids):
    return common.sha256_text(common.spec_hash(["oracle.md", "output-format.md"]) +
                              "".join(arts[i][0].get("source_sha256", "") + arts[i][0].get("spec_sha256", "") for i in sorted(ids)))


def build_question(q, text, arts, force=False):
    ids = sorted(relevant(arts, q))
    digest = inputs_hash(arts, ids)
    path = common.WIKI / "questions" / ("%s.md" % q)
    if path.exists() and not force:
        meta, _ = common.read_front_matter(path.read_text(encoding="utf-8"))
        if meta.get("inputs_sha256") == digest:
            return False, path
    specs = common.spec_text(["oracle.md", "domain-knowledge.md", "output-format.md"])
    body_in = "\n\n".join("<<< wiki/sources/%s.md >>>\n%s" % (i, arts[i][1]) for i in ids) or "(no articles bear on this question)"
    body, model = llm.complete(SYSTEM, "%s\n\nQuestion %s: %s\n\n%s" % (specs, q, text, body_in), max_tokens=5000)
    body = re.sub(r"\A```(?:markdown)?\n|\n```\Z", "", body.strip()).strip()
    meta = {"question": q, "sources": ids, "inputs_sha256": digest, "model": model, "synthesized_at": common.now()}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(common.write_front_matter(meta, body) + "\n", encoding="utf-8")
    return True, path


def short_answer(body):
    m = re.search(r"\*\*Short answer:\*\*\s*(.+?)(?:\n\n|\n#|\Z)", body, re.S)
    return m.group(1).strip() if m else "See the question page."


def write_faq_and_index(arts, questions):
    faq = ["# Frequently asked questions", "",
           "Short answers in the Oracle's voice (`ai_specs/oracle.md`). Each links to its full question page.", ""]
    for q, text in questions.items():
        path = common.WIKI / "questions" / ("%s.md" % q)
        answer = short_answer(common.read_front_matter(path.read_text(encoding="utf-8"))[1]) if path.exists() else "Not yet answered."
        faq += ["## %s. %s" % (q, text), "", answer, "", "[Full answer](questions/%s.md)" % q, ""]
    (common.WIKI / "faq.md").write_text("\n".join(faq), encoding="utf-8")
    idx = ["# Index", "", "Generated by `scripts/synthesize.py`. Do not edit.", "", "## Source articles", "",
           "| ID | Title | Tier | Evidence | Questions |", "| --- | --- | --- | --- | --- |"]
    for sid, (meta, _) in arts.items():
        idx.append("| [%s](sources/%s.md) | %s | %s | %s | %s |" % (
            sid, sid, meta.get("title", ""), meta.get("tier", ""), meta.get("evidence_type", ""),
            ", ".join(meta.get("questions") or [])))
    idx += ["", "## Question pages", ""] + ["- [%s. %s](questions/%s.md)" % (q, t, q) for q, t in questions.items()]
    idx += ["", "[FAQ](faq.md)", ""]
    (common.WIKI / "index.md").write_text("\n".join(idx), encoding="utf-8")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--only")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args(argv)
    arts, questions = articles(), key_questions()
    rebuilt = 0
    for q, text in questions.items():
        if args.only and q not in args.only.split(","):
            continue
        try:
            changed, path = build_question(q, text, arts, args.force)
        except llm.LLMError as exc:
            print("%s LLM unavailable: %s" % (q, exc))
            return 2
        rebuilt += changed
        print("%s %s" % (q, "rebuilt" if changed else "unchanged"))
    write_faq_and_index(arts, questions)
    print("synthesize: %d question pages rebuilt; FAQ and index written" % rebuilt)
    return 0


if __name__ == "__main__":
    sys.exit(main())
